/** The administration panel: the accounts, the subjects, the engine, invitations, settings. */

import type { EvaluatorProfile, FeatureAccessState, FeatureName, GatedName, Role } from "./auth";
import type { ExemplarsProfile } from "./bank";
import type { RunningModel } from "./core";
import type { GenerationListing } from "./generations";
import type { Job } from "./jobs";
import type { ArtifactName, ArtifactStatus } from "./pipeline";
import type { SubjectPeople } from "./workspaces";

/** What `/api/admin/features` answers, and what a write to one function answers too. */
export interface AdminFeaturesPayload {
  features?: Partial<Record<GatedName, Partial<FeatureAccessState>>>;
}

/** Every account's exercises of one workspace, as the administrator's panel reads them. */
export interface AdminGenerationListing extends GenerationListing {
  workspace: string;
  /** Every account with exercises there that still exists, for the filter. */
  authors: { id: number; username: string; name: string | null }[];
  /** The workspace's profile, which draws the rows: the administrator need not be a member. */
  profile: ExemplarsProfile | null;
}

export interface AdminAccount {
  id: number;
  username: string;
  name: string;
  is_admin: boolean;
  evaluator_profile: EvaluatorProfile | null;
  disabled: boolean;
  created_at: string | null;
  /** Its memberships; `disabled` when a teacher paused it (absent from an older API). */
  workspaces: { slug: string; role: Role; disabled?: boolean }[];
  generations: number;
  evaluations: number;
  decided: number;
  /** Sessions usable right now: not revoked and not past either expiry. */
  sessions: number;
  /** Seconds the login rate limiter still refuses this account; 0 when it is not locked. */
  locked_seconds: number;
  email: string | null;
}

export interface DiskUsage {
  raw: number;
  /** The artifacts and their host state, history aside; an older API says `instance`. */
  artifacts?: number;
  cache: number;
  history: number;
  /** Absent from an older API. */
  generations?: number;
  total: number;
}

export interface AdminWorkspace {
  id: number;
  slug: string;
  name: string;
  created_at: string | null;
  members: number;
  generations: number;
  /** Its pipeline context is in memory right now: what the LRU registry is holding. */
  warm: boolean;
  /** Its chain, so a stage can be emptied without switching to that instance. */
  stages: {
    artifact: ArtifactName;
    label: string;
    status: ArtifactStatus;
    is_autogenerated: boolean;
  }[];
  disk: DiskUsage;
  /** Its active owners; empty when nobody owns it. Absent from an older API. */
  owners?: { id: number; username: string; name: string }[];
  /** Who is in it, counted. Absent from an older API. */
  people?: SubjectPeople;
}

export interface AdminOverview {
  totals: {
    users: number;
    workspaces: number;
    generations: number;
    evaluations: number;
    decided: number;
  };
  accounts: AdminAccount[];
  workspaces: AdminWorkspace[];
  engine: {
    busy: boolean;
    job: Job | null;
    queued: number;
    warm_contexts: string[];
  };
}

export interface AdminJobQueue {
  running: Job | null;
  queued: (Job & { queue_position: number })[];
}

export interface TunnelStatus {
  configured: boolean;
  host: string;
  local_port: number | null;
  remote_port: number;
  autostart: boolean;
  /** The administrator asked for it; `running` says whether `ssh` is alive right now. */
  wanted: boolean;
  running: boolean;
  pid: number | null;
  since: number | null;
  attempts: number;
  last_error: string | null;
  stderr: string[];
}

export interface PullStatus {
  model: string;
  status: "running" | "succeeded" | "failed";
  completed: number;
  total: number;
  started_at: number;
  finished_at: number | null;
  error: string | null;
  user: string | null;
}

/** A key, never a label: what a person reads is decided in `lib/i18n`. */
export type ModelResidency = "loaded" | "on_disk" | "not_installed" | "remote";

/** One rolling window of one model's Cerebras quota. `resets_in` is when the oldest call
 *  inside it ages out — the API sends no `reset` header, so the window is reconstructed
 *  from our own timestamps. */
export interface CerebrasWindow {
  requests_used: number;
  requests_limit: number;
  requests_remaining: number;
  tokens_used: number;
  tokens_limit: number;
  tokens_remaining: number;
  resets_in: number;
}

export interface CerebrasPhase {
  phase: string;
  requests: number;
  prompt_tokens: number;
  completion_tokens: number;
  tokens: number;
}

export interface CerebrasModel {
  model: string;
  windows: { minute: CerebrasWindow; day: CerebrasWindow };
  phases: CerebrasPhase[];
}

export interface CerebrasState {
  /** The active engine routes to Cerebras; false means the card is history, not live. */
  active: boolean;
  configured: boolean;
  /** What the configuration sends to Cerebras. */
  routed: string[];
  max_wait: number;
  /** What has actually been spent — empty until the first call, and not the same set. */
  usage: CerebrasModel[];
  /** One call, and the one worth drawing: a call being HELD before the merely running
   *  ones, because that is the state somebody can act on. `inflight_count` says the rest. */
  inflight: {
    model: string;
    phase: string | null;
    since: number;
    elapsed: number;
    /** Set only while the throttle is holding the call back. */
    waiting_until: number | null;
  } | null;
  /** How many calls are in flight at once — more than one since the remote lane got room. */
  inflight_count?: number;
  /** How many jobs may use Cerebras at the same time (`CEREBRAS_MAX_CONCURRENT_JOBS`). */
  concurrency?: number;
}

export interface AdminEngine {
  engine: string;
  host: string;
  available: boolean;
  running: RunningModel[];
  installed: (InstalledModel & { asked_by: string[] })[];
  required: { model: string; asked_by: string[]; state: ModelResidency }[];
  idle: { seconds: number; threshold: number; poll: number };
  busy: boolean;
  contexts: string[];
  pulls: PullStatus[];
  tunnel: TunnelStatus;
  /** Absent when the API is older than this client: version skew must not blank the tab. */
  cerebras?: CerebrasState;
}

/** A class link as the administrator's panel lists it: whose subject, how full, who minted it. */
export interface AdminClassLink {
  id: number;
  workspace: string;
  workspace_name: string;
  /** The group of the class it brings into; null for the whole class. */
  group?: string | null;
  uses: number;
  max_uses: number;
  expires_at: string;
  expired: boolean;
  paused: boolean;
  created_by: string | null;
}

/** Unused and still working, or unused and past its date — which can be moved. */
export type InviteState = "pending" | "expired";

export interface InviteRow {
  id: number;
  /** The administrator's own name for it; whoever holds the link never sees it. */
  label?: string | null;
  role: Role;
  workspace: string | null;
  workspace_slug: string | null;
  created_at: string;
  expires_at: string;
  created_by: string | null;
  state?: InviteState;
  /** Whether the panel can show its link again. False on every one minted before it could. */
  link_stored?: boolean;
  /** The functions whose list the holder joins on registering. Absent from an older API, so
   *  it is read through `lib/invites.inviteFeatures`. */
  features?: unknown;
  /** What the account it creates will be. Read through `lib/invites.inviteProfile`. */
  profile?: unknown;
}

/** What an invitation grants and until when, as the panel sends it. */
export interface InviteTerms {
  workspace: string | null;
  role: Role;
  expires_at: string;
  label: string | null;
  features: FeatureName[];
  profile: EvaluatorProfile;
}

/** An invitation just handed over: its row, its link, and whether that link was kept. */
export interface MintedInvite {
  invite: InviteRow;
  link: string;
  stored?: boolean;
}

/** What pasting a link back did: made a new invitation, made a listed one's link showable, or nothing. */
export type InviteImportOutcome = "created" | "recovered" | "unchanged";

export type ConfigSource = "default" | "file" | "env";

export type ConfigImpact = "none" | "engine" | "contexts" | "reindex" | "locked";

export type ConfigSetting = {
  key: string;
  name: string;
  kind: string;
  group: string;
  impact: ConfigImpact;
  editable: boolean;
  source: ConfigSource;
  env: string | null;
  choices: string[] | null;
  minimum: number | null;
  maximum: number | null;
  nullable: boolean;
  secret: boolean;
  value?: unknown;
  default?: unknown;
  state?: "configurada" | "ausente";
  /** The stages that read it, the one whose screen owns it first. Missing on an older API. */
  stages?: string[];
  /** The model call of that first stage it is drawn under; null governs the whole stage. */
  phase?: string | null;
};

export interface InstalledModel {
  model: string;
  /** Served by a remote provider (Cerebras): listable and selectable, never on this disk. */
  remote?: boolean;
  /** Bytes on disk, as Ollama reports them: an approximation of what it will take resident. */
  size: number | null;
}

export type ReasoningFixed =
  | "grammar"
  | "commission"
  | "model"
  | "drawn"
  | "external"
  | "off";

export type ReasoningPhase = {
  key: string;
  label: string;
  model: string;
  setting: string | null;
  effort: string | null;
  fixed: ReasoningFixed | null;
  note: string;
};

/** One stage's model calls, in the order its work makes them; `key` is the stage. */
export type ReasoningLane = {
  key: string;
  label: string;
  phases: ReasoningPhase[];
};

export type ConfigPayload = {
  /** The stages in the order of the path, the study's last. Missing on an older API. */
  stages?: string[];
  groups: string[];
  settings: ConfigSetting[];
  pipeline: ReasoningLane[];
  /** What the engine offers; both empty when it is unreachable. */
  models: { installed: InstalledModel[]; running: RunningModel[] };
  applied?: string[];
};

export type CerebrasCatalog = {
  models: string[];
  source: "api" | "config";
  error: string | null;
};
