/** Step 3: the types of exercise and the bank, as a teacher and as the class read it. */

export interface FieldSpec {
  schema: Record<string, any>;
  /**
   * What a person reads where this field is shown. Absent falls back to the key, which is
   * an identifier: `solucion` renders as SOLUCION, in an interface that spells everything
   * else properly. Nothing derives it — no accent is recoverable from a key — so it is
   * written by hand, like the modality's own label.
   */
  label?: string;
  description?: string;
  guidance?: { extraction?: string; generation?: string };
  /** Who chooses the value. Absent means "model": only "user" fields are asked for. A build
   *  writes it; no screen edits it. */
  decided_by?: "user" | "model";
  /** Whether a commission may leave this field out of a new exercise. Absent means no:
   *  the field is always written. `true` makes the generate form ask, after the
   *  difficulty, whether this commission's exercises carry it. */
  omittable?: boolean;
}

/** One modality of exercise: its own fields, its own primary and its own rules. */
export interface ItemTypeSpec {
  label?: string;
  description?: string;
  primary_field: string;
  /** Fields read together to decide which concept the item practises. Defaults to
   *  [primary_field]; the solution is deliberately never in it. */
  embed_fields?: string[];
  general_generation_rules?: string[];
  fields: Record<string, FieldSpec>;
}

export interface ExemplarsProfile {
  /** Shared by every modality: it describes the subject, not the exercise. */
  item_types: Record<string, ItemTypeSpec>;
}

export interface ProfilePayload {
  exists: boolean;
  profile: ExemplarsProfile | null;
  path: string | null;
  is_autogenerated?: boolean;
  pending_draft?: import("@/features/profile/drift").ProfilePendingDraft | null;
  /** The difficulty field's canonical name and rungs, as this workspace's prompts write
   *  them. Sent because the editor may have to create one and the name is the workspace's
   *  prompt language's — resolving it in the browser would mean guessing that language. */
  difficulty?: { field: string; levels: string[] };
}

export interface TaggingTrace {
  candidates: [string, number][];
  method:
    | "single_dominant"
    | "llm"
    | "llm_thinking"
    | "llm_wide"
    | "llm_wide_thinking"
    | "rejected"
    | "failed"
    | "no_candidates"
    | "manual";
  model?: string;
  threshold?: number;
}

/** Where an exercise of the bank comes from: the documents, a teacher, or a generated one. */
export type BankOrigin = "extracted" | "manual" | "generated";

/** The account that added an exercise, as the bank names it; null when it no longer exists. */
export interface BankAdder {
  id: number;
  name: string;
  username: string;
}

export interface BankItem {
  id: string;
  source?: string;
  item_type?: string;
  concepts?: string[];
  primary_concept?: string | null;
  _tagging?: TaggingTrace;
  /** Absent on an API older than 2026-10-14, which drew no origin. */
  origin?: BankOrigin;
  added_by?: BankAdder | null;
  /** ISO 8601, UTC. */
  added_at?: string;
  /** What the subject's students see of it: nothing (null), all of it, or the fields chosen,
   *  the statement always among them. Absent on an older API. */
  visibility?: BankVisibility | null;
  /** Whether it is one of the asking teacher's stars. */
  favourite?: boolean;
  [field: string]: unknown;
}

/** Who sees an exercise of the bank: the level chosen and the fields it shows. */
export interface BankVisibility {
  level: "full" | "fields";
  fields: string[];
  /** The groups of the class that see it; null (or absent, on an older API) is the whole
   *  class. */
  groups?: number[] | null;
}

/**
 * An exercise of the bank as the class reads it (`GET /api/exercises`): the fields its
 * teacher showed, named in `shown` in the type's order, its level and its concepts, and
 * nothing else of it.
 */
export interface ReadableExercise {
  id: string;
  item_type: string;
  shown: string[];
  concepts: string[];
  primary_concept: string | null;
  [field: string]: unknown;
}

/** The bank as the class reads it: the shape of `BankListing`, without a teacher's figures. */
export interface ExerciseListing {
  items: ReadableExercise[];
  total: number;
  page: number;
  page_size: number;
  item_types: BankItemType[];
  difficulties: { value: string; count: number }[];
  default_type: string | null;
  /** The concepts the exercises read carry, each with its unit, in the syllabus' order:
   *  what the concept filter offers. */
  concepts?: { name: string; unit: string | null }[];
}

/** One exercise a re-extraction could not keep: it no longer fits its type. */
export interface SetAsideItem {
  key: string;
  /** The id it had in the bank. */
  id: string;
  at: string | null;
  item: Record<string, unknown>;
}

/** What `POST /api/bank` takes: an exercise written by hand, and who decides its concepts. */
export interface NewBankItem {
  item_type: string | null;
  fields: Record<string, unknown>;
  tag: "auto" | "manual";
  concepts?: string[];
  primary_concept?: string | null;
  /** An exercise a re-extraction put aside, brought back as it was. */
  set_aside?: string;
  /** What the class sees of it from the start; hidden when absent. */
  visibility?: { level: "hidden" | "full" | "fields"; fields: string[]; groups?: number[] | null };
}

export interface BankItemType {
  key: string;
  label: string;
  description: string;
  primary_field: string;
  embed_fields: string[];
  fields: string[];
  /** Which of this modality's fields carries the difficulty, or null when it declares
   *  none. Named by the server because the key is the workspace's prompt language's. */
  difficulty_field: string | null;
  /** Its rungs, in the order the modality declares them. The same three in every modality,
   *  which is what lets one column and one sort read across a mixed list. */
  difficulty_levels: string[];
  count: number;
}

export interface BankListing {
  items: BankItem[];
  total: number;
  page: number;
  page_size: number;
  item_types: BankItemType[];
  /** Every rung the profile declares, with how many items of the whole bank sit on it —
   *  declared and not gathered, so a rung nobody has written is still selectable. */
  difficulties: { value: string; count: number }[];
  default_type: string;
  /** The documents the collected exercises came from. */
  sources: string[];
  /** How many exercises of each origin; absent on an older API, and with it this whole
   *  phase's controls (the origin badges and filter, «Añadir ejercicio»). */
  origins?: Record<BankOrigin, number>;
  /** How many the students see, how many carry the asking teacher's star, and how many
   *  collected ones carry either. Absent on an older API, and with it the marks' controls. */
  marks?: { visible: number; favourites: number; extracted: number };
  totals: { items: number; tagged: number; untagged: number };
  thresholds: { similarity: number; top_k: number };
}

export interface Coverage {
  counts: Record<string, number>;
  covered: number;
  total: number;
  without_exemplars: string[];
}
