/** The chain of the three steps: each stage's state, its build plans and the subject's context. */

import type { Job, JobKind, Lanes } from "./jobs";
import type { RawKind } from "./raw";

export type ArtifactName = "exemplars_profile" | "knowledge_graph" | "exemplars_bank";

export type ArtifactStatus = "missing" | "building" | "draft" | "approved" | "stale";

/**
 * Why a stage is stale. Two shapes share it: an ARTIFACT above changed (`artifact`), or the
 * DOCUMENTS the stage was built from did (`slot`, with the three lists). `reason` is the
 * server's own Spanish sentence and is the fallback for a cause this bundle cannot phrase.
 */
export interface StaleCause {
  artifact?: ArtifactName;
  slot?: RawKind;
  label: string;
  reason: string;
  added?: string[];
  removed?: string[];
  changed?: string[];
}

export interface StageState {
  artifact: ArtifactName;
  label: string;
  status: ArtifactStatus;
  hash: string | null;
  path: string | null;
  is_autogenerated: boolean;
  approved_at: string | null;
  stale_because: StaleCause[];
  blocked_by: string[];
  blocked_reason: string | null;
  build_job: JobKind;
  /** The raw slot this stage's build reads, while a transcription of it is live: the
   *  build waits for it. Absent on an API older than the bundle, which reads as "none". */
  transcribing_slot?: RawKind | null;
  /** Whether a hand edit leaves the stage closed (the bank's exercises, since 2026-10-14).
   *  Absent on an older API, where every edit reopens it. */
  edits_keep_closed?: boolean;
}

export interface Pipeline {
  stages: StageState[];
  generation_unlocked: boolean;
  /** The running job **of this workspace**; null when the GPU is busy with someone else's. */
  current_job: Job | null;
  queued: number;
  queue_length: number;
  queue_ahead: number | null;
  /** Somebody, anybody, is holding the one GPU. The honest reason a job has not started. */
  engine_busy: boolean;
  engine_busy_elsewhere: boolean;
  /** Absent when the API is older than this bundle: version skew must not blank a screen,
   *  so every reader goes through `readLanes` and falls back to the flat queue counters. */
  lanes?: Lanes;
}

/**
 * One phase of a build: what it is called and what share of the bar it owns.
 *
 * A weight is a share of the WORK and never of the clock. There is no time estimate
 * anywhere: what a phase costs is a claim about the models the instance is pointed at, and
 * it goes stale silently the moment the config does.
 */
export interface BuildPhase {
  key: string;
  label: string;
  weight: number;
}

export interface BuildPlans {
  artifacts: Record<ArtifactName, BuildPhase[]>;
  /** Plans of jobs that write no artifact and still have phases. */
  jobs: Partial<Record<JobKind, BuildPhase[]>>;
}

/**
 * What the free-text field of a commission may and may not ask for.
 *
 * Derived by the server from this instance's own artifacts, so another workspace answers
 * something else without a line changing here. The terms each owner decides stay on the
 * server: the screen names the control, never its values.
 */
export interface CommissionScope {
  slots: { key: string; label: string; example: string }[];
  owners: { key: string; label: string; where: string }[];
  facts: { key: string; value: string }[];
}

/** The subject's context: prose plus the three facts the naive arm reads by name. */
export interface ContentContextState {
  exists: boolean;
  narrative: string;
  facts: Record<string, string>;
  block: string;
  source: "curated" | "draft" | null;
  path: string | null;
  /** The text the last build synthesised and the curated one is covering. */
  pending_draft: string | null;
  canonical_keys: string[];
}
