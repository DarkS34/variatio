export type ArtifactName = "content_profile" | "knowledge_graph" | "exemplars_bank";

export type ArtifactStatus = "missing" | "building" | "draft" | "approved" | "stale";

export type JobKind =
  | "build_profile"
  | "build_kg"
  | "build_bank"
  | "describe_concepts"
  | "index"
  | "tag"
  | "generate";

export type JobStatus = "queued" | "running" | "succeeded" | "failed" | "cancelled";

export interface StaleCause {
  artifact: ArtifactName;
  label: string;
  reason: string;
}

export interface StageState {
  artifact: ArtifactName;
  label: string;
  status: ArtifactStatus;
  hash: string | null;
  path: string | null;
  is_autogenerated: boolean;
  approved_at: string | null;
  stale_because: StaleCause[];
  blocked_by: string[];
  blocked_reason: string | null;
  build_job: JobKind;
}

export interface Pipeline {
  stages: StageState[];
  generation_unlocked: boolean;
  current_job: Job | null;
  queued: number;
}

export interface Job {
  id: string;
  kind: JobKind;
  params: Record<string, unknown>;
  status: JobStatus;
  created_at: number;
  started_at: number | null;
  finished_at: number | null;
  error: string | null;
  result: Record<string, any> | null;
  label: string;
  artifact: ArtifactName | null;
  elapsed_ms: number | null;
}

export interface Health {
  engine: string;
  host: string;
  available: boolean;
  models: { required: Record<string, string>; installed: string[]; missing: string[] };
  context_ready: boolean;
  paths: {
    instance: string;
    raw_exemplars: string;
    raw_corpus: string;
    raw_exemplars_exists: boolean;
    raw_corpus_exists: boolean;
  };
  busy: boolean;
}

/* Raw source data ------------------------------------------------------------------ */

export type RawKind = "corpus" | "exemplars";

export interface RawFile {
  name: string;
  bytes: number;
  modified: number;
  extension: string;
}

export interface RawSlot {
  kind: RawKind;
  label: string;
  purpose: string;
  feeds: ArtifactName[];
  path: string;
  exists: boolean;
  files: RawFile[];
  bytes: number;
}

export interface RawListing {
  supported_extensions: string[];
  max_bytes: number;
  slots: RawSlot[];
}

export interface RawUpload {
  added: { name: string; bytes: number; renamed: boolean }[];
  rejected: { name: string; reason: string }[];
  slot: RawSlot;
}

/* Content profile ------------------------------------------------------------------ */

export interface FieldSpec {
  schema: Record<string, any>;
  description?: string;
  guidance?: { extraction?: string; generation?: string };
}

export interface ContentProfile {
  content_context: Record<string, string>;
  general_generation_rules: string[];
  primary_field: string;
  fields: Record<string, FieldSpec>;
}

export interface ProfilePayload {
  exists: boolean;
  profile: ContentProfile | null;
  path: string | null;
  is_autogenerated?: boolean;
}

/* Knowledge graph ------------------------------------------------------------------ */

export interface KgConcept {
  name: string;
  domain: string;
  taggable: boolean;
  degree: number;
  description: string | null;
  exemplars: number;
}

export interface KgSummary {
  path: string;
  domains: { name: string; concepts: string[] }[];
  concepts: KgConcept[];
  relations: { name: string; details: Record<string, any>; edges: number }[];
  totals: {
    domains: number;
    concepts: number;
    taggable: number;
    described: number;
    with_exemplars: number;
  };
}

export interface GraphView {
  meta: { title: string; kind: string; generated: string; isolated: number };
  relations: { key: string; verbose?: string; directed: boolean; count: number }[];
  groups: { name: string; count: number }[];
  /** [name, groupIndex, nonTaggable] */
  nodes: [string, number, number][];
  /** [sourceIndex, targetIndex, relationIndex] */
  links: [number, number, number][];
}

/* Exemplars bank ------------------------------------------------------------------- */

export interface TaggingTrace {
  candidates: [string, number][];
  method: "single_dominant" | "llm" | "llm_thinking" | "rejected" | "failed" | "no_candidates" | "manual";
  model?: string;
  threshold?: number;
  margin?: number;
}

export interface BankItem {
  id: string;
  source?: string;
  concepts?: string[];
  primary_concept?: string | null;
  _tagging?: TaggingTrace;
  [field: string]: unknown;
}

export interface BankListing {
  items: BankItem[];
  total: number;
  page: number;
  page_size: number;
  primary_field: string;
  fields: string[];
  sources: string[];
  totals: { items: number; tagged: number; untagged: number };
  thresholds: { similarity: number; relative_margin: number };
}

export interface Coverage {
  counts: Record<string, number>;
  covered: number;
  total: number;
  without_exemplars: string[];
}

/* Events --------------------------------------------------------------------------- */

export interface VgEvent {
  seq: number;
  ts: number;
  job_id: string | null;
  kind: string;
  [payload: string]: any;
}
