def build_exemplars_profile(ws: Workspace | None = None) -> dict:
    ws = _artifacts.resolve(ws)

    logger.info("Construyendo el borrador del perfil de ejemplares")

    profile = ExemplarsProfileBuilder(workspace=ws).build(
        ws.raw_exemplars_dir, ws.exemplars_profile_autogenerated_path
    )

    if not profile:
        raise RuntimeError(f"Could not draft a exemplars profile from {ws.raw_exemplars_dir}")

    return profile


def build_knowledge_graph(ws: Workspace | None = None) -> dict:
    ws = _artifacts.resolve(ws)
    logger.info("Construyendo el borrador del grafo de conocimiento")
    return KnowledgeGraphBuilder(workspace=ws).build(ws.raw_corpus_dir)


# Extraer y etiquetar son un solo trabajo desde 2026-08-22: cada documento se etiqueta
# nada más salir del extractor y se guarda ya anotado. Eran dos pasos que había que lanzar
# a mano uno detrás del otro, y el segundo no era opcional — un banco sin etiquetar no
# sirve ni para generar ni para indexar. Etiquetar por documento en vez de al final tiene
# además el efecto que el arranque en caliente ya explotaba entre ejecuciones: los ítems
# del documento 3 se etiquetan contra un índice que ya contiene los de los documentos 1 y 2.
def build_exemplars_bank(
    exemplars_profile: ExemplarsProfile | None = None,
    ws: Workspace | None = None,
) -> dict:
    ws = _artifacts.resolve(ws)
    if exemplars_profile is None:
        path = _artifacts.exemplars_profile_path(ws)
        if path is None:
            raise _artifacts.MissingArtifactError(_artifacts.EXEMPLARS_PROFILE)
        exemplars_profile = ExemplarsProfile(path)

    logger.info("Construyendo el banco de ejemplares")
    bank = ExemplarsBankBuilder(
        exemplars_profile,
        workspace=ws,
        content_context=_artifacts.load_content_context(ws),
    ).build(
        ws.raw_exemplars_dir,
        ws.exemplars_bank_path,
        on_items=_tagging_hook(ws, exemplars_profile),
    )
    if not bank:
        raise RuntimeError(f"Could not build an exemplars bank from {ws.raw_exemplars_dir}")
    return bank


# Sin grafo no hay con qué etiquetar, y eso no es un error: el banco se extrae igual y
# queda pendiente de `stages.tag_bank`, que es como funcionaba hasta ahora.
def _tagging_hook(ws: Workspace, exemplars_profile: ExemplarsProfile):
    kg_path = _artifacts.knowledge_graph_path(ws)
    if kg_path is None:
        logger.warning(
            "No hay grafo de conocimiento: los ítems se extraen sin etiquetar"
        )
        return None

    # Perezoso a propósito: construir el `Embedder` indexa todos los conceptos y escribe
    # las descripciones que falten, y eso son minutos. Hacerlo aquí lo pondría ANTES de la
    # primera fase del plan, con la barra parada en 0 %; hacerlo en la primera llamada lo
    # pone dentro de la fase que ya lo está contando.
    state: dict = {}

    def ready():
        if not state:
            content_context = _artifacts.load_content_context(ws)
            embedder = make_embedder(
                ws, exemplars_profile, KnowledgeGraph(kg_path), content_context
            )
            state["embedder"] = embedder
            state["tagger"] = make_tagger(embedder, exemplars_profile, content_context)
        return state["embedder"], state["tagger"]

    def annotate(bank: dict, new_ids: list[str]) -> dict:
        embedder, tagger = ready()
        # El índice se refresca con el banco completo antes de etiquetar: vectoriza solo
        # lo nuevo (el resto se reutiliza de la caché) y vuelve a fundir los centroides,
        # que es lo que hace que las etiquetas de los documentos anteriores cuenten.
        embedder.enrich_index_with_content(bank)
        working = dict(bank)

        # Se guarda tras cada ítem por lo mismo que en `stages/tag.py`: cancelar a mitad
        # conserva todas las decisiones ya tomadas.
        def checkpoint(item_id: str, item: dict) -> None:
            working[item_id] = item
            write_json(ws.exemplars_bank_path, working)

        try:
            return tagger.tag_all(bank, ids=new_ids, on_item=checkpoint)
        except BaseException:
            write_json(ws.exemplars_bank_path, working)
            raise

    return annotate


_BUILDERS = {
    _artifacts.EXEMPLARS_PROFILE: build_exemplars_profile,
    _artifacts.KNOWLEDGE_GRAPH: build_knowledge_graph,
    _artifacts.EXEMPLARS_BANK: build_exemplars_bank,
}


_LABELS = {
    _artifacts.EXEMPLARS_PROFILE: "Perfil de ejemplares",
    _artifacts.KNOWLEDGE_GRAPH: "Grafo de conocimiento",
    _artifacts.EXEMPLARS_BANK: "Banco de ejemplares",
}

# Each builder declares what its phases cost; installing the plan here is what turns
# "some step is running" into a percentage of the whole build, for all three alike.
_PHASES = {
    _artifacts.EXEMPLARS_PROFILE: exemplars_profile_builder.BUILD_PHASES,
    _artifacts.KNOWLEDGE_GRAPH: knowledge_graph_builder.BUILD_PHASES,
    _artifacts.EXEMPLARS_BANK: exemplars_bank_builder.BUILD_PHASES,
}


def build_phases(artifact: str) -> tuple[tuple[str, str, int], ...]:
    """The `(key, label, weight)` plan a build of this artifact will run through."""
    if artifact not in _PHASES:
        raise ValueError(f"Unknown artifact '{artifact}'; expected one of {list(_PHASES)}")
    return _PHASES[artifact]


def build_artifact(artifact: str, ws: Workspace | None = None) -> dict:
    if artifact not in _BUILDERS:
        raise ValueError(f"Unknown artifact '{artifact}'; expected one of {list(_BUILDERS)}")

    with progress.step(f"build_{artifact}", f"Construyendo: {_LABELS[artifact]}"), progress.overall(_PHASES[artifact]):
        return _BUILDERS[artifact](ws=ws)


def build_missing(ws: Workspace | None = None) -> list[str]:
    ws = _artifacts.resolve(ws)
    missing = _artifacts.missing_artifacts(ws)
    for artifact in missing:
        progress.checkpoint()
        build_artifact(artifact, ws)
    return missing
