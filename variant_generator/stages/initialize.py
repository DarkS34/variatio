from dataclasses import dataclass
from functools import partial
from pathlib import Path

from loguru import logger

from .. import config, progress
from ..concept_tagger import ConceptTagger
from ..content_generator import ContentGenerator
from ..exemplars_profile import ExemplarsProfile
from ..embedder import Embedder
from ..exemplars_bank import ExemplarsBank
from ..knowledge_graph import KnowledgeGraph
from ..workspace import Workspace
from . import _artifacts


@dataclass
class PipelineContext:
    exemplars_profile: ExemplarsProfile
    knowledge_graph: KnowledgeGraph
    embedder: Embedder
    exemplars_bank: dict
    tagger: ConceptTagger
    generator: ContentGenerator
    exemplars_profile_path: Path
    knowledge_graph_path: Path
    workspace: Workspace

    # The bank is the one artifact that changes while the context is alive (tagging,
    # manual edits). Swapping it means re-embedding and re-merging the index; doing it
    # here keeps embedder and generator from drifting apart.
    def apply_bank(self, bank: dict) -> None:
        self.exemplars_bank = bank
        self.embedder.enrich_index_with_content(bank)
        self.generator.exemplars_bank = bank


def initialize(tag: bool = False, ws: Workspace | None = None) -> PipelineContext:
    """Load the instance and warm the indices.

    Read-only by default: tagging is a separate, explicit act (`stages.tag_bank`)
    because it rewrites the exemplars bank. `tag=True` restores the old all-in-one
    behaviour the CLI relies on.
    """
    ws = _artifacts.resolve(ws)

    profile_path = _artifacts.exemplars_profile_path(ws)
    if profile_path is None:
        raise _artifacts.MissingArtifactError(_artifacts.EXEMPLARS_PROFILE)
    if profile_path == ws.exemplars_profile_autogenerated_path:
        logger.warning(f"Using auto-drafted exemplars profile: {profile_path}")

    kg_path = _artifacts.knowledge_graph_path(ws)
    if kg_path is None:
        raise _artifacts.MissingArtifactError(_artifacts.KNOWLEDGE_GRAPH)
    if kg_path == ws.kg_autogenerated_path:
        logger.warning(
            f"Using auto-drafted KG for this run: {kg_path} — "
            f"curate it manually into {ws.kg_path.name}"
        )

    with progress.step("load_instance", "Cargando la instancia (perfil, grafo y banco)"):
        bank = ExemplarsBank(ws.exemplars_bank_path).bank
        if bank is None:
            raise _artifacts.MissingArtifactError(_artifacts.EXEMPLARS_BANK)

        exemplars_profile = ExemplarsProfile(profile_path)
        knowledge_graph = KnowledgeGraph(kg_path)

        logger.info(
            f"Exemplars profile: {len(exemplars_profile.item_types)} item type(s) — "
            + "; ".join(
                f"{key} ({len(t.field_specs)} field(s), indexed by "
                f"{'+'.join(t.embed_fields)})"
                for key, t in exemplars_profile.item_types.items()
            )
            + f" ({profile_path.name})"
        )

        # Everything downstream resolves each item against the type it declares, so a bank
        # extracted before a type was added or renamed would fail deep inside the embedding
        # loop. One aggregated error here names the artifact that has to be rebuilt.
        unplaceable = exemplars_profile.unplaceable_items(bank)
        if unplaceable:
            sample = list(unplaceable.items())[:5]
            raise ValueError(
                f"{len(unplaceable)} bank item(s) do not match the exemplars profile "
                f"({profile_path.name}); the bank was built against a different one and "
                f"has to be rebuilt. First: "
                + "; ".join(f"{item_id}: {reason}" for item_id, reason in sample)
            )
        oversized = exemplars_profile.oversized_embed_items(
            bank, config.EMBEDDING_MAX_CHARS, config.EMBEDDING_FIELD_MAX_CHARS
        )
        if oversized:
            worst = sorted(oversized.items(), key=lambda pair: -pair[1])[:5]
            logger.warning(
                f"{len(oversized)} bank item(s) exceed the {config.EMBEDDING_MAX_CHARS:,}-char "
                f"embedding budget and may be truncated when indexed or rejected when tagged: "
                + "; ".join(f"{item_id} ({size:,})" for item_id, size in worst)
            )

        logger.info(
            f"Knowledge graph: {len(knowledge_graph.all_concepts)} concept(s), "
            f"{len(knowledge_graph.taggable_concepts)} taggable, "
            f"{len(knowledge_graph.relation_details)} relation type(s) ({kg_path.name})"
        )
        logger.info(
            f"Exemplars bank: {len(bank)} item(s), "
            f"{sum(1 for item in bank.values() if item.get('concepts'))} already tagged"
        )

    embed_text = partial(
        exemplars_profile.embed_text, field_max_chars=config.EMBEDDING_FIELD_MAX_CHARS
    )
    embedder = Embedder(
        knowledge_graph,
        config.EMBEDDING_LLM,
        embed_text=embed_text,
        embed_signature=exemplars_profile.embed_signature,
        context=exemplars_profile.content_context,
        descriptions_path=ws.concept_descriptions_path,
        concepts_cache_path=ws.concepts_embeddings_path,
        exemplars_bank_cache_path=ws.exemplars_bank_embeddings_path,
    )
    tagger = ConceptTagger(
        embedder,
        config.CONCEPT_TAGGER_LLM,
        embed_text=embed_text,
        context=exemplars_profile.content_context,
    )
    generator = ContentGenerator(
        knowledge_graph=knowledge_graph,
        exemplars_bank=bank,
        embedder=embedder,
        exemplars_profile=exemplars_profile,
        generator_model=config.CONTENT_GENERATION_LLM,
    )

    context = PipelineContext(
        exemplars_profile=exemplars_profile,
        knowledge_graph=knowledge_graph,
        embedder=embedder,
        exemplars_bank=bank,
        tagger=tagger,
        generator=generator,
        exemplars_profile_path=profile_path,
        knowledge_graph_path=kg_path,
        workspace=ws,
    )

    if tag:
        from .tag import tag_bank

        tag_bank(context)
    else:
        embedder.enrich_index_with_content(bank)

    return context
