"""Reading and editing the subject's context.

Not a stage, so not in `review.ARTIFACTS`: it has no `raw/` slot and no build of its own.
The two builders synthesise it as the last thing they do, each from what its own artifact
knows about the subject, and each writes the DRAFT. What is edited here is the CURATED file,
which is what wins on read — that pair is what stops a rebuild from paraphrasing somebody's
words one more time.
"""

from variatio.core.workspace import Workspace
from variatio.instance.content_context import ContentContext

from .. import storage

HISTORY_NAME = "content_context"


def adopt_draft(ws: Workspace) -> dict:
    """Save the draft's own text as the curated context. Raises ValueError with no draft.

    From here on the draft is the curated file, and the next build writes a new draft
    beside it rather than over it.
    """
    draft = ContentContext.load(ws.content_context_autogenerated_path)
    if not draft:
        raise ValueError("No hay ningún borrador de contexto que adoptar.")
    return save(ws, draft.narrative, dict(draft.facts))


def save(ws: Workspace, narrative: str, facts: dict[str, str]) -> dict:
    """Write the curated context and read it back."""
    context = ContentContext({"narrative": narrative, **facts})
    # Through `storage` rather than `ContentContext.save`, so the edit gets a history
    # snapshot like every other artifact edit.
    storage.write_json(ws.content_context_path, context.as_dict(), ws=ws, artifact=HISTORY_NAME)
    return load(ws)


def load(ws: Workspace) -> dict:
    """Read the context that wins — curated over draft — with the unread draft beside it.

    A build always writes the draft, so once the context is curated a newer synthesis sits
    there unread. Reporting it as `pending_draft` is the whole point of keeping both files:
    otherwise a rebuild would look as though it had left the context alone.
    """
    curated = ws.content_context_path
    draft = ws.content_context_autogenerated_path
    has_curated = curated.is_file()
    has_draft = draft.is_file()
    path = curated if has_curated else draft if has_draft else None
    context = ContentContext.load(path)

    return {
        "exists": path is not None,
        "narrative": context.narrative,
        "facts": dict(context.facts),
        "block": context.prompt_block(),
        "source": "curated" if has_curated else "draft" if has_draft else None,
        "path": str(path) if path is not None else None,
        "pending_draft": (
            ContentContext.load(draft).narrative if has_curated and has_draft else None
        ),
    }
