from pathlib import Path

from variatio import stages
from variatio.core.workspace import Workspace as FsWorkspace

from .models import CURATED, DRAFT

KINDS = (stages.KNOWLEDGE_GRAPH, stages.EXEMPLARS_PROFILE, stages.EXEMPLARS_BANK)


def artifact_paths(ws: FsWorkspace) -> dict[str, dict[str, Path]]:
    return {
        stages.KNOWLEDGE_GRAPH: {CURATED: ws.kg_path, DRAFT: ws.kg_autogenerated_path},
        stages.EXEMPLARS_PROFILE: {
            CURATED: ws.exemplars_profile_path,
            DRAFT: ws.exemplars_profile_autogenerated_path,
        },
        stages.EXEMPLARS_BANK: {CURATED: ws.exemplars_bank_path},
    }


def locate(ws: FsWorkspace, path: Path) -> tuple[str, str] | None:
    target = Path(path).resolve()
    for kind, stage_paths in artifact_paths(ws).items():
        for stage, candidate in stage_paths.items():
            if candidate.resolve() == target:
                return kind, stage
    return None
