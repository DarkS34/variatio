"""The chain of artifacts and its approval gates.

Each artifact is built, reviewed and approved before the next one is unlocked.
Approving records the artifact's own hash *and* the hash of everything it was
derived from; if an upstream later changes, the downstream is marked stale and
the UI can offer to redo that step. Nothing repairs itself behind the user's back.
"""

import json
from datetime import datetime
from pathlib import Path

from variant_generator import stages
from variant_generator.core import json_io
from variant_generator.core.workspace import Workspace

from . import storage

EXEMPLARS_PROFILE = stages.EXEMPLARS_PROFILE
KNOWLEDGE_GRAPH = stages.KNOWLEDGE_GRAPH
EXEMPLARS_BANK = stages.EXEMPLARS_BANK

ARTIFACTS: tuple[str, ...] = (EXEMPLARS_PROFILE, KNOWLEDGE_GRAPH, EXEMPLARS_BANK)

# This tuple is the chain as the screens draw it — the navbar and the panel's cards read
# it, so it has to be the order a person actually works in. It is the LAYOUT that says the
# order; the cards carry no ordinal (removed 2026-08-22), because a number next to a card
# that is already third from the left only adds a second place for the two to disagree.
#
# The profile leads since 2026-08-21, and that is no longer just presentation. Building the
# graph still needs nothing (`UPSTREAM[KNOWLEDGE_GRAPH]` is `()` and must stay so — a build
# reads only the raw corpus). But FINISHING it does: the taggability review is a job of its
# own now and `routers/jobs.NEEDS_APPROVED` gates it on an APPROVED profile, because a
# concept is useless as a label only relative to the shapes of item this instance sets.
# Starting a workspace with the graph therefore walks you into a stage you cannot complete.
# The bank still comes last, and that one IS forced by `UPSTREAM`: it needs the profile's
# schema to extract and the graph's concepts to tag.
UPSTREAM: dict[str, tuple[str, ...]] = {
    KNOWLEDGE_GRAPH: (),
    EXEMPLARS_PROFILE: (),
    EXEMPLARS_BANK: (EXEMPLARS_PROFILE, KNOWLEDGE_GRAPH),
}

LABELS = {
    EXEMPLARS_PROFILE: "Perfil de ejemplares",
    KNOWLEDGE_GRAPH: "Grafo de conocimiento",
    EXEMPLARS_BANK: "Banco de ejemplares",
}

STALE_ACTION = {
    (EXEMPLARS_BANK, EXEMPLARS_PROFILE): "El esquema cambió: los ítems se extrajeron con el anterior.",
    (EXEMPLARS_BANK, KNOWLEDGE_GRAPH): "El grafo cambió: las etiquetas apuntan a conceptos anteriores.",
}


def canonical_path(ws: Workspace, artifact: str) -> Path:
    """Where an edit is written. Editing a draft promotes it to the curated file."""
    return {
        EXEMPLARS_PROFILE: ws.exemplars_profile_path,
        KNOWLEDGE_GRAPH: ws.kg_path,
        EXEMPLARS_BANK: ws.exemplars_bank_path,
    }[artifact]


def autogenerated_path(ws: Workspace, artifact: str) -> Path | None:
    return {
        EXEMPLARS_PROFILE: ws.exemplars_profile_autogenerated_path,
        KNOWLEDGE_GRAPH: ws.kg_autogenerated_path,
    }.get(artifact)


def current_path(ws: Workspace, artifact: str) -> Path | None:
    if artifact == EXEMPLARS_PROFILE:
        return stages.exemplars_profile_path(ws)
    if artifact == KNOWLEDGE_GRAPH:
        return stages.knowledge_graph_path(ws)
    path = ws.exemplars_bank_path
    return path if path.is_file() else None


# What stops making sense as soon as the artifact is gone. These are regenerable
# derivations, not user data: the `.npz` are rebuilt by indexing and the descriptions are
# written again. Deleting them is what keeps the next build from starting on the cache of
# a graph that no longer exists.
DERIVED: dict[str, tuple[str, ...]] = {
    KNOWLEDGE_GRAPH: (
        "concept_descriptions_path",
        "concept_sources_path",
        "concepts_embeddings_path",
    ),
    EXEMPLARS_PROFILE: (),
    EXEMPLARS_BANK: ("exemplars_bank_embeddings_path", "eval_rag_bank_embeddings_path"),
}


def artifact_files(ws: Workspace, artifact: str) -> list[Path]:
    """The files that ARE the artifact: the curated one and, if there is one, its draft."""
    draft = autogenerated_path(ws, artifact)
    paths = [canonical_path(ws, artifact)] + ([draft] if draft else [])
    return [path for path in paths if path.is_file()]


def _derived_files(ws: Workspace, artifact: str) -> list[Path]:
    paths: list[Path] = []
    for attribute in DERIVED[artifact]:
        path = getattr(ws, attribute)
        # `concept_descriptions.fingerprints.json` lives beside the file it describes and only
        # the describer names it; it is collected by adjacency so that rule is not duplicated.
        paths += [path, path.with_suffix(f".fingerprints{path.suffix}")]
    return [path for path in paths if path.is_file()]


# Empties a stage: the artifact goes back to «missing» and can be rebuilt. It does NOT
# touch `.history/`, which is precisely how a mistaken deletion is undone.
def discard(ws: Workspace, artifact: str) -> dict:
    files = artifact_files(ws, artifact)
    derived = _derived_files(ws, artifact)
    for path in files + derived:
        path.unlink(missing_ok=True)
    ReviewState(ws).reopen(artifact)
    return {
        "artifact": artifact,
        "removed": [str(path) for path in files],
        "derived": [str(path) for path in derived],
    }


# One instance per workspace, constructed where it is needed rather than kept as a
# singleton: it holds a path and reads a small JSON, so there is nothing to cache and
# nothing to keep in sync between two instances of two different workspaces.
class ReviewState:
    def __init__(self, ws: Workspace, path: Path | None = None):
        self.ws = ws
        self.path = Path(path or ws.review_state_path)

    # PERSISTENCE ---------------------------------------------------------------------------

    def _load(self) -> dict:
        if not self.path.is_file():
            return {}
        try:
            with self.path.open(encoding="utf-8") as f:
                return json.load(f)
        except (json.JSONDecodeError, OSError):
            return {}

    def _save(self, data: dict) -> None:
        json_io.write_json(self.path, data)

    # TRANSITIONS ---------------------------------------------------------------------------

    def approve(self, artifact: str) -> dict:
        path = current_path(self.ws, artifact)
        digest = storage.sha256_of(path)
        if digest is None:
            raise FileNotFoundError(f"'{artifact}' does not exist yet")

        data = self._load()
        data[artifact] = {
            "status": "approved",
            "hash": digest,
            "upstream": {
                up: storage.sha256_of(current_path(self.ws, up)) for up in UPSTREAM[artifact]
            },
            "at": datetime.now().isoformat(timespec="seconds"),
        }
        self._save(data)
        return data[artifact]

    def reopen(self, artifact: str) -> None:
        data = self._load()
        data.pop(artifact, None)
        self._save(data)

    def invalidate(self, artifact: str) -> None:
        """Called after an edit: the artifact goes back to draft, gates close behind it."""
        self.reopen(artifact)

    # READ ----------------------------------------------------------------------------------

    def state(self, artifact: str, building: set[str] | None = None) -> dict:
        building = building or set()
        path = current_path(self.ws, artifact)
        digest = storage.sha256_of(path)
        record = self._load().get(artifact)

        if artifact in building:
            status = "building"
        elif digest is None:
            status = "missing"
        elif record is None or record.get("status") != "approved":
            status = "draft"
        elif record.get("hash") != digest:
            status = "draft"
        else:
            status = "approved"

        stale_because: list[dict] = []
        if status == "approved":
            for upstream in UPSTREAM[artifact]:
                recorded = (record.get("upstream") or {}).get(upstream)
                if recorded != storage.sha256_of(current_path(self.ws, upstream)):
                    stale_because.append(
                        {
                            "artifact": upstream,
                            "label": LABELS[upstream],
                            "reason": STALE_ACTION.get(
                                (artifact, upstream), f"{LABELS[upstream]} cambió."
                            ),
                        }
                    )
            if stale_because:
                status = "stale"

        draft_path = autogenerated_path(self.ws, artifact)
        return {
            "artifact": artifact,
            "label": LABELS[artifact],
            "status": status,
            "hash": digest,
            "path": str(path) if path else None,
            "is_autogenerated": bool(path and draft_path and Path(path) == draft_path),
            "approved_at": record.get("at") if record else None,
            "stale_because": stale_because,
        }

    def snapshot(self, building: set[str] | None = None) -> list[dict]:
        states = {a: self.state(a, building) for a in ARTIFACTS}
        result = []
        for artifact in ARTIFACTS:
            state = states[artifact]
            blockers = [
                LABELS[up]
                for up in UPSTREAM[artifact]
                if states[up]["status"] != "approved"
            ]
            state["blocked_by"] = blockers
            state["blocked_reason"] = (
                f"Aprueba primero: {', '.join(blockers)}." if blockers else None
            )
            result.append(state)
        return result

    def gate_open(self, artifact: str) -> bool:
        """True when everything this artifact depends on has been approved."""
        return all(self.state(up)["status"] == "approved" for up in UPSTREAM[artifact])

    def generation_unlocked(self) -> bool:
        return all(self.state(a)["status"] == "approved" for a in ARTIFACTS)
